// mcpDiagnosis.ts — MCP-aware diagnosis with fix patch generation

import { diagnoseAgent, DiagnosisResult, Issue, AgentConfig } from './diagnosisEngine';
import { generateFixPatches, patchesToMarkdown, FixPatch } from '../services/fixGenerator';

export interface MCPDiagnosisResult extends DiagnosisResult {
  repoUrl: string;
  filesAnalyzed: number;
  fixPatches: FixPatch[];
  mcpToolsUsed: string[];
  mrUrl?: string;
  mrIid?: number;
  branchName?: string;
}

export interface DiagnosisProgressEvent {
  type: 'file_discovered' | 'file_read' | 'file_analyzed' | 'issue_found' | 'fix_generated' | 'branch_created' | 'mr_created' | 'error' | 'complete';
  message: string;
  data?: unknown;
}

export function runMCPDiagnosis(
  files: { path: string; content: string }[],
  repoUrl: string,
  agentType: string,
  agentName: string,
  mcpToolsUsed: string[]
): MCPDiagnosisResult {
  const config: AgentConfig = {
    agentName,
    agentType,
    files,
  };

  const result = diagnoseAgent(config);
  const fixPatches = generateFixPatches(result.issues);

  return {
    ...result,
    repoUrl,
    filesAnalyzed: files.length,
    fixPatches,
    mcpToolsUsed,
  };
}

export function buildMRDescription(result: MCPDiagnosisResult): string {
  const severityIcon: Record<string, string> = {
    CRITICAL: '🔴',
    HIGH: '🟠',
    MEDIUM: '🟡',
    LOW: '🔵',
    HEALTHY: '🟢',
  };

  let md = `# 🏥 AgentICU Diagnosis Report — ${result.patientId}\n\n`;
  md += `> **Agent:** ${result.agentName} | **Type:** ${result.agentType} | **Scanned:** ${result.filesAnalyzed} files | **MCP Tools Used:** ${(result.mcpToolsUsed || []).join(', ')}\n\n`;

  md += `## 📊 Health Score: ${result.healthScore}/100 — **${result.status}**\n\n`;
  md += `${severityIcon[result.status] ?? '⚪'} Overall status: ${result.status}\n`;
  md += `📅 ${result.timestamp}\n\n`;

  md += `## 📋 Summary\n\n${result.summary}\n\n`;

  if (result.criticalPath && result.criticalPath !== 'No critical path — agent is healthy!') {
    md += `## ⚠️ Critical Path\n\n\`\`\`\n${result.criticalPath}\n\`\`\`\n\n`;
  }

  md += `## 🔍 Issues Detected (${result.issues.length})\n\n`;
  if (result.issues.length === 0) {
    md += '✅ No issues detected. Agent is healthy!\n\n';
  } else {
    for (const issue of result.issues) {
      const icon = severityIcon[issue.status] ?? '⚪';
      md += `### ${icon} ${issue.name} [${issue.id}] — Severity: ${issue.severity}/10\n\n`;
      md += `**Category:** ${issue.category}\n`;
      md += `**Evidence:** ${issue.evidence}\n\n`;
      md += `**Treatment:**\n`;
      for (const step of issue.treatment) {
        md += `- ${step}\n`;
      }
      if (issue.file) {
        md += `\n*Detected in: \`${issue.file}\`*\n`;
      }
      md += '\n---\n\n';
    }
  }

  if (result.fixPatches.length > 0) {
    md += patchesToMarkdown(result.fixPatches);
  }

  md += `\n---\n*Generated by AgentICU v2 — Google Cloud Rapid Agent Hackathon*\n`;
  return md;
}

export { patchesToMarkdown, generateFixPatches };
export type { FixPatch } from '../services/fixGenerator';
